/**
 * Правила полей адреса — те же, что на сайте (frontend/src/shared/lib/address.ts).
 * Не проверяют, что такой дом существует, но отсекают явную бессмыслицу вроде «вау, кв. уца».
 */

/** Улица: не короче 3 символов, хотя бы 3 русские буквы, без посторонних знаков. */
export const STREET_RE =
  /^(?=(?:[^А-Яа-яЁё]*[А-Яа-яЁё]){3})[А-Яа-яЁёA-Za-z0-9 .,()№/«»"'-]{3,200}$/;

/** Дом: 45, 45а, 45/2, 45 к2, 45 корп. 1, 12 стр. 3. */
export const HOUSE_RE =
  /^\d{1,4} ?[А-Яа-яЁёA-Za-z]?( ?[/-] ?\d{1,4}[А-Яа-яЁёA-Za-z]?)?( ?(к|корп\.?|корпус|с|стр\.?|строение) ?\d{1,3}[А-Яа-яЁё]?)?$/i;

/** Подъезд: номер. */
export const ENTRANCE_RE = /^\d{1,2}$/;

/** Квартира: 12, 12а. */
export const APARTMENT_RE = /^\d{1,5} ?[А-Яа-яЁёA-Za-z]?$/;

